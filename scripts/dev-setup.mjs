// Writes apps/gateway/.dev.vars for local development with freshly generated keys.
// Existing files are left untouched unless --force is passed.
import { existsSync, writeFileSync } from 'node:fs'

const path = new URL('../apps/gateway/.dev.vars', import.meta.url)
if (existsSync(path) && !process.argv.includes('--force')) {
  console.log('apps/gateway/.dev.vars already exists (use --force to regenerate)')
  process.exit(0)
}

const encryptionKey = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString('base64url')
const { privateKey } = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify'])
const { kty, crv, x, y, d } = await crypto.subtle.exportKey('jwk', privateKey)

writeFileSync(path, [
  '# Local development only. Generated by scripts/dev-setup.mjs.',
  'PUBLIC_BASE_URL=http://localhost:8787',
  'MCP_BASE_URL=http://127.0.0.1:8787',
  'DATABASE_URL=http://root:unused@127.0.0.1:3900',
  'DATABASE_HOST=unused',
  'DATABASE_USERNAME=unused',
  'DATABASE_PASSWORD=unused',
  'DEV_OWNER=dev-user',
  'ALLOW_LOOPBACK_APPS=true',
  `ENCRYPTION_KEY=${encryptionKey}`,
  `ASSERTION_PRIVATE_JWK=${JSON.stringify({ kty, crv, x, y, d, kid: 'dev' })}`,
  '',
].join('\n'))
console.log('Wrote apps/gateway/.dev.vars')
